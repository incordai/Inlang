/**
 * The injection corpus (fixtures/chat-attacks/, chat-block-spec §6.1, §12)
 * against the filter: each hostile answer, replayed by the `fake` model,
 * must become exactly its expected events — through the answer parser
 * alone, and through POST /chat end to end — with the dropped components
 * counted, and none of the model's words in the log. The same cases run
 * through the real page in three browsers in scripts/chat-e2e.mjs.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { createApp } from '../src/server/app.ts';
import { createFakeAdapter, parseFakeScript } from '../src/server/chat-adapters.ts';
import { createAnswerParser, type AnswerEvent, type AnswerRules } from '../src/server/chat-answer.ts';
import { createSseReader } from '../src/server/chat-sse.ts';
import { historyKey, checkTag } from '../src/server/chat-text.ts';
import { createUsage, migrateChat, utcDay } from '../src/server/chat-usage.ts';
import { createChat, parseChatContext } from '../src/server/chat.ts';
import { migrate, openSqlite } from '../src/server/db.ts';
import { loadConfig } from '../src/server/env.ts';
import { createOidc } from '../src/server/oidc.ts';
import { createStore } from '../src/server/store.ts';
import { client, listen, SECRET, SITE } from './helpers.ts';
import { chunksOf, corpusCases, corpusRules } from './chat-corpus.ts';

const CASES = corpusCases();
const RULES: AnswerRules = corpusRules();

/** Text events joined, blocks in order: how the page reads a stream, whatever its pieces. */
function outcome(events: readonly AnswerEvent[]): { text: string; blocks: unknown[] } {
  let text = '';
  const blocks: unknown[] = [];
  for (const e of events) {
    if (e.type === 'text') text += e.s;
    else blocks.push(e.block);
  }
  return { text, blocks };
}

test('the corpus covers every threat of §6.1 the filter answers for', () => {
  const names = CASES.map((c) => c.name);
  for (const n of ['legal', 'forbidden-words', 'scripts', 'schemes', 'hosts', 'markdown', 'entities', 'unicode', 'nesting', 'long-line', 'composed-pricing', 'css', 'too-many', 'over-long', 'unterminated', 'forged-notes', 'forged-quote', 'short-forms', 'forged-use']) {
    assert.ok(names.includes(n), n);
  }
  // CONTROL: the legal case shows every component; every other case refuses or neutralises something.
  assert.equal(CASES.find((c) => c.name === 'legal')!.expect.blocks.length, 4);
});

for (const c of CASES) {
  test(`corpus ${c.name} — the parser: ${c.threat}`, () => {
    for (const pieces of [[c.answer], chunksOf(c.answer)]) {
      const p = createAnswerParser(RULES);
      const events: AnswerEvent[] = [];
      for (const piece of pieces) {
        if (p.ended) break;
        events.push(...p.push(piece));
      }
      events.push(...p.end());
      assert.deepEqual({ ...outcome(events), dropped: [...p.dropped], ...(c.expect.history !== undefined ? { history: p.history() } : {}) }, c.expect);
    }
  });
}

test('the corpus through POST /chat: every case streams exactly its events; drops are counted, never logged with text', async () => {
  const loaded = loadConfig({
    AZ_SESSION_SECRET: SECRET, AZ_BACKEND_PUBLIC_URL: 'http://127.0.0.1:9', AZ_ALLOWED_ORIGINS: SITE,
    AZ_EMAIL_FROM: 'Lantern <no-reply@lantern.test>', AZ_SMTP_HOST: '127.0.0.1', AZ_SMTP_PORT: '2525',
    AZ_CHAT_API: 'fake', AZ_CHAT_FAKE_FILE: '/unused-in-process.json', AZ_CHAT_PER_ADDRESS: '1000/hour', AZ_CHAT_DAILY_TOKENS: '100000000',
  }, { database: 'sqlite', email: 'smtp', chat: true }, 'Lantern');
  if (!loaded.ok) throw new Error(loaded.problems.join('\n'));
  const db = await openSqlite(':memory:');
  await migrate(db);
  await migrateChat(db);
  const script = parseFakeScript(JSON.stringify({ answers: CASES.map((x) => ({ when: x.ask, chunks: chunksOf(x.answer) })) }));
  if (typeof script === 'string') throw new Error(script);
  const context = parseChatContext(JSON.stringify({
    site: { name: 'Lantern' }, pages: [], routes: ['/ask'],
    chats: { '/ask': { allow: 'anyone', limit: 50, prompt: 'prompt-1.txt', show: RULES.show, presets: RULES.presets } },
    answer: { quotes: RULES.quotes, destinations: RULES.destinations },
  }));
  if (typeof context === 'string') throw new Error(context);
  const log: string[] = [];
  const chat = createChat({
    config: loaded.config.chat!, secret: loaded.config.secret, db, prompts: { 'prompt-1.txt': '# GENERATED BY AZ — test\nYou answer about Lantern.\n' },
    context, adapter: createFakeAdapter(script), log: (l) => log.push(l),
  });
  const app = createApp({
    config: loaded.config, store: createStore(db, loaded.config.secret), mailer: { send: async () => {} }, oidc: createOidc(fetch),
    log: (l) => log.push(l), chat,
  });
  const server = createServer((q, r) => { void app.handler(q, r); });
  const url = await listen(server);
  try {
    let dropped = 0;
    for (const x of CASES) {
      const r = await client(url).post('/chat', { page: '/ask', messages: [{ role: 'visitor', text: x.ask }] });
      assert.equal(r.status, 200, x.name);
      const reader = createSseReader();
      const raw = [...reader.push(new Uint8Array(await r.arrayBuffer())), ...reader.end()];
      // The closed set of events, and nothing else on the wire.
      assert.ok(raw.every((e) => ['text', 'block', 'done'].includes(e.event)), `${x.name}: ${raw.map((e) => e.event).join(' ')}`);
      const events: AnswerEvent[] = raw.filter((e) => e.event !== 'done')
        .map((e) => (e.event === 'text' ? { type: 'text', s: JSON.parse(e.data).s } : { type: 'block', block: JSON.parse(e.data) }));
      assert.deepEqual(outcome(events), { text: x.expect.text, blocks: x.expect.blocks }, x.name);
      const done = JSON.parse(raw.at(-1)!.data) as { tag: string; conversation: string; text: string };
      // The history is tagged: it is what the page may send back, and nothing it may not (§19.14).
      assert.ok(checkTag(historyKey(loaded.config.secret), done.conversation, 1, done.text, done.tag), x.name);
      if (x.expect.history !== undefined) assert.equal(done.text, x.expect.history, `${x.name}: the history the model is sent back`);
      dropped += x.expect.dropped.length;
    }
    const usage = await createUsage(db).row(utcDay(Date.now()));
    assert.equal(usage?.messages, CASES.length);
    assert.equal(usage?.dropped, dropped, 'every dropped component counted');
    const all = log.join('\n');
    assert.match(all, /dropped \d+ \(/, 'drops are logged as counts and reasons');
    for (const word of ['evil.example', 'alert(', 'lumens', 'Team is free', '<script', 'zzzz']) assert.equal(all.includes(word), false, word);
  } finally {
    server.closeAllConnections();
    server.close();
    await db.close();
  }
});
