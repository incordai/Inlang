/**
 * `az backend probe` (server chat-probe.ts, chat-block-spec §11.3): the
 * production prompt and context sent to a model, one question per
 * component, each answer measured and parsed — against a local fake model
 * server speaking the completions shape, in process and as the CLI runs it
 * from a server folder. Bounded; the key is never printed.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import { createCompletionsAdapter } from '../src/server/chat-adapters.ts';
import { parseChatContext } from '../src/server/chat.ts';
import { PROBE_MS, PROBE_QUESTIONS, probeChat, probeReport } from '../src/server/chat-probe.ts';

const SERVER_SRC = fileURLToPath(new URL('../src/server/', import.meta.url));
const CLI = fileURLToPath(new URL('../../cli/bin/az.js', import.meta.url));
const RUN_MS = 60_000;
const KEY = `probe-key-${randomBytes(8).toString('hex')}`;

const CONTEXT_JSON = JSON.stringify({
  site: { name: 'Shop' }, pages: [{ route: '/', blocks: [] }], routes: ['/', '/contact', '/plans'],
  chats: { '/': { allow: 'anyone', limit: 20, prompt: 'prompt-1.txt', show: ['pricing', 'faq', 'cta', 'feature'] } },
  answer: { quotes: [{ word: 'pricing', route: '/plans', n: 0 }], destinations: ['/', '/contact', '/plans'] },
});
const context = (() => { const c = parseChatContext(CONTEXT_JSON); if (typeof c === 'string') throw new Error(c); return c; })();

/** What a well-behaved model answers to each fixed question. */
const GOOD: Readonly<Record<string, string>> = {
  [PROBE_QUESTIONS.prose]: 'Shop sells lamps. It ships worldwide.',
  [PROBE_QUESTIONS.pricing]: 'Team fits most.\nshow pricing /plans',
  [PROBE_QUESTIONS.faq]: 'faq\n  item "Do you ship?"\n    text "Yes."',
  [PROBE_QUESTIONS.cta]: 'Start here.\ncta "Contact us" /contact',
  [PROBE_QUESTIONS.feature]: 'feature\n  item "Bright"\n    text "800 lumens."',
};

type Reply = (question: string) => { status?: number; text?: string; stall?: boolean };

/** A local model server: each answer streamed in two deltas, then usage, then [DONE]. `seen` keeps every request. */
async function modelServer(reply: Reply) {
  const seen: { auth: string | undefined; body: { model: string; messages: { role: string; content: string }[]; max_tokens: number } }[] = [];
  const server = createServer(async (req: IncomingMessage, res: ServerResponse) => {
    let raw = '';
    for await (const c of req) raw += c;
    const body = JSON.parse(raw);
    seen.push({ auth: req.headers.authorization, body });
    const r = reply(body.messages.at(-1).content);
    if (r.stall) return;
    if (r.status) { res.writeHead(r.status).end('{"error":"provider body that must never be shown"}'); return; }
    const text = r.text ?? '';
    const half = Math.floor(text.length / 2);
    res.writeHead(200, { 'content-type': 'text/event-stream' });
    for (const d of [text.slice(0, half), text.slice(half)]) res.write(`data: ${JSON.stringify({ choices: [{ delta: { content: d } }] })}\n\n`);
    res.write(`data: ${JSON.stringify({ choices: [], usage: { prompt_tokens: 1200, completion_tokens: 30 } })}\n\n`);
    res.end('data: [DONE]\n\n');
  });
  await new Promise<void>((r) => server.listen(0, '127.0.0.1', r));
  const url = `http://127.0.0.1:${(server.address() as { port: number }).port}/v1`;
  return { url, seen, close: () => new Promise<void>((r) => { server.closeAllConnections(); server.close(() => r()); }) };
}

const probe = (url: string, extra: Partial<Parameters<typeof probeChat>[0]> = {}) => probeChat({
  adapter: createCompletionsAdapter({ url, key: KEY, model: 'candidate-model' }),
  prompts: { 'prompt-1.txt': '# GENERATED BY AZ — test\nYou answer about Shop.\n' }, context, maxOutputTokens: 600, timeoutMs: 10_000, ...extra,
});

test('a model that answers every question in the forms passes: streamed, timed, its tokens, each component parsed', async () => {
  const m = await modelServer((q) => ({ text: GOOD[q] }));
  try {
    const r = await probe(m.url);
    assert.equal(r.ok, true, probeReport(r));
    assert.deepEqual(r.answers.map((a) => a.question), ['prose', 'pricing', 'faq', 'cta', 'feature']);
    for (const a of r.answers) {
      assert.equal(a.outcome, 'ok');
      assert.equal(a.streamed, true);
      assert.ok(a.firstMs !== null && a.firstMs <= a.totalMs);
      assert.deepEqual(a.tokens, { input: 1200, output: 30 });
      assert.deepEqual(a.dropped, []);
    }
    assert.deepEqual(r.answers.map((a) => a.events.blocks), [{}, { quote: 1 }, { faq: 1 }, { cta: 1 }, { feature: 1 }]);
    // The production prompt and context: the system text the chat route would send.
    const system = m.seen[0].body.messages[0];
    assert.equal(system.role, 'system');
    assert.match(system.content, /You answer about Shop\.\n\n<site-content>/);
    assert.match(system.content, /quote one that answers rather than write your own:\nshow pricing \/plans\n/);
    assert.equal(m.seen[0].body.model, 'candidate-model');
    assert.equal(m.seen[0].body.max_tokens, 600);
    assert.equal(m.seen[0].auth, `Bearer ${KEY}`);
    assert.doesNotMatch(probeReport(r), new RegExp(KEY));
    assert.match(probeReport(r), /^PASS pricing {2}\/ · outcome ok · streamed yes · first \d+ms · total \d+ms · tokens 1200\/30 · text events \d+ · components quote×1 · dropped none$/m);
  } finally { await m.close(); }
});

test('a model that writes a component the filter drops, answers nothing, or fails, fails the probe — saying why, never what it wrote', async () => {
  const m = await modelServer((q) => (q === PROBE_QUESTIONS.cta ? { text: 'Here.\ncta "Claim" https://evil.example/' }
    : q === PROBE_QUESTIONS.faq ? { text: '' }
      : q === PROBE_QUESTIONS.feature ? { status: 500 } : { text: GOOD[q] }));
  try {
    const r = await probe(m.url);
    assert.equal(r.ok, false);
    const by = Object.fromEntries(r.answers.map((a) => [a.question, a]));
    assert.deepEqual(by.cta.dropped, ['destination']);
    assert.equal(by.faq.outcome, 'empty');
    assert.equal(by.feature.outcome, 'unavailable status 500');
    const report = probeReport(r);
    assert.match(report, /^FAIL cta /m);
    assert.match(report, /probe: FAILED/);
    for (const word of ['evil.example', 'Claim', 'provider body', KEY]) assert.equal(report.includes(word), false, word);
  } finally { await m.close(); }
});

test('bounded: a model that never answers times out at the first-token bound; past the whole budget questions are not asked', async () => {
  const m = await modelServer((q) => (q === PROBE_QUESTIONS.prose ? { stall: true } : { text: GOOD[q] }));
  try {
    const started = Date.now();
    const r = await probe(m.url, { timing: { firstMs: 300, betweenMs: 300 } });
    assert.equal(r.answers[0].outcome, 'timeout');
    assert.ok(Date.now() - started < 8_000, `${Date.now() - started}ms`);
    const none = await probe(m.url, { budgetMs: 0 });
    assert.ok(none.answers.every((a) => a.outcome === 'not_asked'));
    assert.equal(none.ok, false);
  } finally { await m.close(); }
  assert.ok(PROBE_MS <= 10 * 60 * 1000);
});

/** A built server folder with a chat, its .env pointing at `url`. */
function serverDir(url: string, extra: readonly string[] = []): string {
  const dir = mkdtempSync(join(tmpdir(), 'az-chat-probe-'));
  cpSync(SERVER_SRC, join(dir, 'src'), { recursive: true });
  writeFileSync(join(dir, 'az.config.json'), JSON.stringify({ siteName: 'Shop', database: 'sqlite', email: 'api', chat: true }));
  mkdirSync(join(dir, 'chat'));
  writeFileSync(join(dir, 'chat/prompt-1.txt'), '# GENERATED BY AZ — test\nAnswer about Shop.\n');
  writeFileSync(join(dir, 'chat/context.json'), CONTEXT_JSON);
  writeFileSync(join(dir, '.env'), [
    `AZ_SESSION_SECRET=${randomBytes(32).toString('base64url')}`, 'AZ_BACKEND_PUBLIC_URL=http://127.0.0.1:9', 'AZ_ALLOWED_ORIGINS=http://localhost:5173',
    `AZ_SQLITE_PATH=${join(dir, 'data/app.db')}`, 'AZ_EMAIL_FROM=Shop <no-reply@shop.test>', 'AZ_EMAIL_API_URL=https://mail.invalid/send', 'AZ_EMAIL_API_KEY=<PLACEHOLDER>',
    'AZ_CHAT_API=completions', `AZ_CHAT_URL=${url}`, `AZ_CHAT_KEY=${KEY}`, 'AZ_CHAT_MODEL=candidate-model', ...extra, '',
  ].join('\n'));
  return dir;
}

/** `az backend probe <dir>`, run as a person would, bounded. */
function cli(dir: string, ...flags: string[]): Promise<{ code: number | null; out: string }> {
  return new Promise((done) => {
    const child = spawn(process.execPath, [CLI, 'backend', 'probe', dir, ...flags], { stdio: ['ignore', 'pipe', 'pipe'], env: { PATH: process.env.PATH } });
    let out = '';
    child.stdout.on('data', (c) => { out += c; });
    child.stderr.on('data', (c) => { out += c; });
    const timer = setTimeout(() => child.kill('SIGKILL'), RUN_MS);
    child.once('exit', (code) => { clearTimeout(timer); done({ code, out }); });
  });
}

test('az backend probe <server-dir>: reads the server\'s .env and chat files, exits 0 on a good model and 1 on a bad one, never prints the key', async () => {
  const good = await modelServer((q) => ({ text: GOOD[q] }));
  const bad = await modelServer(() => ({ status: 401 }));
  const dirs = [serverDir(good.url), serverDir(bad.url)];
  try {
    const ok = await cli(dirs[0]);
    assert.equal(ok.code, 0, ok.out);
    assert.match(ok.out, /^probe: completions model "candidate-model" at http:\/\/127\.0\.0\.1:\d+$/m);
    assert.equal((ok.out.match(/^PASS /gm) ?? []).length, 5, ok.out);
    const json = await cli(dirs[0], '--json');
    assert.equal(JSON.parse(json.out.slice(json.out.indexOf('{'))).ok, true);
    const no = await cli(dirs[1]);
    assert.equal(no.code, 1, no.out);
    assert.match(no.out, /outcome unavailable status 401/);
    for (const r of [ok, json, no]) assert.equal(r.out.includes(KEY), false, 'the key is never printed');
    // CONTROL: a folder that is not a chat server is refused before anything runs.
    const plain = await cli(tmpdir());
    assert.equal(plain.code, 1);
    assert.match(plain.out, /no built server with a chat/);
  } finally {
    await good.close();
    await bad.close();
    for (const d of dirs) rmSync(d, { recursive: true, force: true });
  }
});

/** A local data tool (chat-block-spec §21.2): `/ok` answers two rows of the declared fields, `/bad` a row of another shape. */
async function toolServer() {
  const seen: { path: string; body: string; auth: string | undefined }[] = [];
  const server = createServer(async (req: IncomingMessage, res: ServerResponse) => {
    let body = '';
    for await (const c of req) body += c;
    seen.push({ path: req.url ?? '', body, auth: req.headers.authorization });
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify(req.url === '/ok' ? [{ driver: 'Ana', points: 25 }, { driver: 'Ben', points: 18 }] : [{ driver: 'Ana' }]));
  });
  await new Promise<void>((r) => server.listen(0, '127.0.0.1', r));
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  return { base, seen, close: () => new Promise<void>((r) => { server.closeAllConnections(); server.close(() => r()); }) };
}

const TOOL_KEY = `probe-tool-key-${randomBytes(8).toString('hex')}`;
const toolEnv = (url: string) => [
  'AZ_CHAT_TOOLS=standings', `AZ_CHAT_TOOL_STANDINGS_URL=${url}`, `AZ_CHAT_TOOL_STANDINGS_KEY=${TOOL_KEY}`,
  `AZ_CHAT_TOOL_STANDINGS_PARAMS=${JSON.stringify({ season: { type: 'int', min: 2000, max: 2030, required: true } })}`,
  `AZ_CHAT_TOOL_STANDINGS_FIELDS=${JSON.stringify({ driver: 'text', points: 'number' })}`,
  'AZ_CHAT_TOOL_STANDINGS_LABEL=Race results service', `AZ_CHAT_TOOL_STANDINGS_SAMPLE=${JSON.stringify({ season: 2026 })}`,
];

test('az backend probe calls each data tool once with its sample: a tool of the declared shape passes, one of another fails the probe; the key is never printed', async () => {
  const good = await modelServer((q) => ({ text: GOOD[q] }));
  const tool = await toolServer();
  const dirs = [serverDir(good.url, toolEnv(`${tool.base}/ok`)), serverDir(good.url, toolEnv(`${tool.base}/bad`))];
  try {
    const ok = await cli(dirs[0]);
    assert.equal(ok.code, 0, ok.out);
    assert.match(ok.out, /^PASS tool standings · outcome ok · total \d+ms · rows 2$/m);
    assert.match(ok.out, /every tool answered rows of its declared fields$/m);
    assert.deepEqual(tool.seen.map((s) => [s.path, JSON.parse(s.body), s.auth]), [['/ok', { season: 2026 }, `Bearer ${TOOL_KEY}`]], 'once, with the sample and the key');
    // This site's chat shows no chart, table or stats: the model is not told of the tools.
    assert.ok(good.seen.every((s) => !s.body.messages[0].content.includes('from tool')));
    const bad = await cli(dirs[1]);
    assert.equal(bad.code, 1, bad.out);
    assert.match(bad.out, /^FAIL tool standings · outcome shape · total \d+ms · rows 0$/m);
    for (const r of [ok, bad]) {
      assert.equal(r.out.includes(TOOL_KEY), false, 'the tool key is never printed');
      assert.equal(r.out.includes(tool.base), false, 'nor its URL');
    }
  } finally {
    await good.close();
    await tool.close();
    for (const d of dirs) rmSync(d, { recursive: true, force: true });
  }
});

test('§19.17: the probe notes a chat whose fixed system text is under the cache minimum — never a failure; AZ_CHAT_CACHE_MIN_TOKENS=0 says nothing', async () => {
  const m = await modelServer((q) => ({ text: GOOD[q] ?? 'Fine.' }));
  try {
    const r = await probe(m.url, { cacheMinTokens: 1024 });
    assert.equal(r.ok, true, 'a short prefix is still a working chat');
    assert.deepEqual(r.cache?.under.map((u) => u.page), ['/']);
    assert.ok(r.cache!.under[0].tokens > 0 && r.cache!.under[0].tokens < 1024);
    assert.match(probeReport(r), /^NOTE cache: 1 of 1 chat page sends a fixed system text of about \d+ tokens, under the provider's prompt-cache minimum of 1024 \(AZ_CHAT_CACHE_MIN_TOKENS\): \//m);
    // CONTROL: past the minimum, and with none, there is no note.
    assert.deepEqual((await probe(m.url, { cacheMinTokens: 10 })).cache?.under, []);
    const none = await probe(m.url);
    assert.equal(none.cache, undefined);
    assert.doesNotMatch(probeReport(none), /NOTE cache/);
  } finally { await m.close(); }
});
