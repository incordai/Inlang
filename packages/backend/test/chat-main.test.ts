/**
 * The generated server's entry point with a chat (main.ts), started for
 * real from a copied server folder: it answers /chat through the `fake`
 * model, refuses `fake` off loopback, and a server copied WITHOUT the
 * chat modules (a site without a chat) still starts — nothing imports them
 * statically.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn, spawnSync, type ChildProcess } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createServer, type AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';

const SERVER_SRC = fileURLToPath(new URL('../src/server/', import.meta.url));
const START_MS = 20_000;
const STOP_MS = 5_000;
const FETCH_MS = 10_000;
const SITE = 'http://localhost:5173';

const freePort = () => new Promise<number>((ok, fail) => {
  const probe = createServer();
  probe.once('error', fail);
  probe.listen(0, '127.0.0.1', () => { const { port } = probe.address() as AddressInfo; probe.close(() => ok(port)); });
});

/** A server folder: `chat` writes the chat files and keeps the chat modules; without it they are left out, as the CLI copies. */
function serverDir(chat: boolean): string {
  const dir = mkdtempSync(join(tmpdir(), 'az-chat-main-'));
  cpSync(SERVER_SRC, join(dir, 'src'), { recursive: true, filter: (src) => chat || !/[\\/]chat[^\\/]*\.ts$/.test(src) });
  writeFileSync(join(dir, 'az.config.json'), JSON.stringify({ siteName: 'Shop', database: 'sqlite', email: 'api', ...(chat ? { chat: true } : {}) }));
  if (chat) {
    mkdirSync(join(dir, 'chat'));
    writeFileSync(join(dir, 'chat/prompt.txt'), '# GENERATED BY AZ — test\nAnswer about Shop.\n');
    writeFileSync(join(dir, 'chat/context.json'), JSON.stringify({ site: { name: 'Shop' }, pages: [], chats: { '/': { allow: 'anyone', limit: 5 } }, routes: ['/'] }));
    writeFileSync(join(dir, 'fake.json'), JSON.stringify({ answers: [{ chunks: ['Hi ', 'from the fake.'] }] }));
  }
  return dir;
}

const env = (dir: string, port: number, extra: Record<string, string> = {}) => ({
  PATH: process.env.PATH,
  AZ_SESSION_SECRET: randomBytes(32).toString('base64url'),
  AZ_BACKEND_PUBLIC_URL: `http://127.0.0.1:${port}`, AZ_ALLOWED_ORIGINS: SITE, AZ_PORT: String(port),
  AZ_SQLITE_PATH: join(dir, 'data/app.db'),
  AZ_EMAIL_FROM: 'Shop <no-reply@shop.test>', AZ_EMAIL_API_URL: 'https://mail.invalid/send', AZ_EMAIL_API_KEY: '<PLACEHOLDER>',
  ...extra,
});

async function started(child: ChildProcess): Promise<{ ok: boolean; log: () => string }> {
  let log = '';
  const ok = await new Promise<boolean>((done) => {
    const timer = setTimeout(() => done(false), START_MS);
    const read = (c: Buffer) => {
      log += c;
      if (log.includes('backend: listening on')) { clearTimeout(timer); done(true); }
    };
    child.stdout!.on('data', read);
    child.stderr!.on('data', read);
    child.once('exit', () => { clearTimeout(timer); done(false); });
  });
  return { ok, log: () => log };
}

async function stop(child: ChildProcess): Promise<void> {
  const exited = new Promise<boolean>((ok) => child.once('exit', () => ok(true)));
  child.kill('SIGTERM');
  const gone = await Promise.race([exited, new Promise<boolean>((ok) => setTimeout(() => ok(false), STOP_MS).unref())]);
  if (!gone) child.kill('SIGKILL');
}

test('a chat server starts, migrates az_chat_usage, and answers POST /chat as a stream', async () => {
  const dir = serverDir(true);
  const port = await freePort();
  const child = spawn(process.execPath, ['src/main.ts'], {
    cwd: dir, stdio: ['ignore', 'pipe', 'pipe'],
    env: env(dir, port, { AZ_CHAT_API: 'fake', AZ_CHAT_FAKE_FILE: join(dir, 'fake.json') }),
  });
  try {
    const s = await started(child);
    assert.ok(s.ok, s.log());
    assert.match(s.log(), /backend: applied chat migrations 1/);
    const r = await fetch(`http://127.0.0.1:${port}/chat`, {
      method: 'POST', signal: AbortSignal.timeout(FETCH_MS),
      headers: { origin: SITE, 'x-az-request': '1', 'content-type': 'application/json' },
      body: JSON.stringify({ page: '/', messages: [{ role: 'visitor', text: 'hello' }] }),
    });
    assert.equal(r.status, 200);
    const body = await r.text();
    // Prose streams through the answer parser: each piece but its last character, which waits for what may combine with it.
    assert.match(body, /^event: text\ndata: \{"s":"Hi"\}\n\nevent: text\ndata: \{"s":" from the fake"\}\n\nevent: text\ndata: \{"s":"\."\}\n\nevent: done\ndata: \{"tag":"[A-Za-z0-9_-]+","left":4,"conversation":"[A-Za-z0-9_-]+","text":"Hi from the fake\.","share":\{"at":\d+,"tag":"[A-Za-z0-9_-]{43}","tagq":"[A-Za-z0-9_-]{43}"\}\}\n\n$/);
  } finally {
    await stop(child);
    rmSync(dir, { recursive: true, force: true });
  }
});

test('the fake model off loopback: the server refuses to start, naming it', () => {
  const dir = serverDir(true);
  const r = spawnSync(process.execPath, ['src/main.ts'], {
    cwd: dir, encoding: 'utf8', timeout: START_MS, killSignal: 'SIGKILL',
    env: env(dir, 18788, { AZ_BACKEND_PUBLIC_URL: 'https://api.shop.test', AZ_CHAT_API: 'fake', AZ_CHAT_FAKE_FILE: join(dir, 'fake.json') }),
  });
  try {
    assert.equal(r.status, 1, r.stderr);
    assert.match(r.stderr, /AZ_CHAT_API=fake is for development only/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('a broken scripted-answers file stops the start with its problem, not a stack', () => {
  const dir = serverDir(true);
  writeFileSync(join(dir, 'fake.json'), '{"answers": []}');
  const r = spawnSync(process.execPath, ['src/main.ts'], {
    cwd: dir, encoding: 'utf8', timeout: START_MS, killSignal: 'SIGKILL',
    env: env(dir, 18789, { AZ_CHAT_API: 'fake', AZ_CHAT_FAKE_FILE: join(dir, 'fake.json') }),
  });
  try {
    assert.equal(r.status, 1, r.stderr);
    assert.match(r.stderr, /AZ_CHAT_FAKE_FILE needs \{ "answers": \[ … \] \}/);
    assert.doesNotMatch(r.stderr, /\n\s+at /);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('a server without the chat modules (a site without a chat) starts and answers /chat 404', async () => {
  const dir = serverDir(false);
  assert.ok(!readdirSync(join(dir, 'src')).some((f) => f.startsWith('chat')), 'CONTROL: no chat module was copied');
  const port = await freePort();
  const child = spawn(process.execPath, ['src/main.ts'], { cwd: dir, stdio: ['ignore', 'pipe', 'pipe'], env: env(dir, port) });
  try {
    const s = await started(child);
    assert.ok(s.ok, s.log());
    const r = await fetch(`http://127.0.0.1:${port}/chat`, {
      method: 'POST', signal: AbortSignal.timeout(FETCH_MS),
      headers: { origin: SITE, 'x-az-request': '1', 'content-type': 'application/json' }, body: '{}',
    });
    assert.equal(r.status, 404);
  } finally {
    await stop(child);
    rmSync(dir, { recursive: true, force: true });
  }
});
