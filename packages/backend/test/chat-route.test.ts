interface Started {
  url: string; log: string[]; fake: ReturnType<typeof createFakeAdapter>; chat: ChatConfig;
  db: Awaited<ReturnType<typeof openSqlite>>; close(): Promise<void>;
}

async function startChat(env: Record<string, string> = {}, over: { timing?: ChatTiming; timeoutMs?: number } = {}): Promise<Started> {
  const loaded = loadConfig({
    AZ_SESSION_SECRET: SECRET, AZ_BACKEND_PUBLIC_URL: 'http://127.0.0.1:9', AZ_ALLOWED_ORIGINS: SITE,
    AZ_EMAIL_FROM: 'Studio <no-reply@studio.test>', AZ_SMTP_HOST: '127.0.0.1', AZ_SMTP_PORT: '2525',
    AZ_CHAT_API: 'fake', AZ_CHAT_FAKE_FILE: '/unused-in-process.json',
    ...env,
  }, { database: 'sqlite', email: 'smtp', chat: true }, 'Studio');
  if (!loaded.ok) throw new Error(loaded.problems.join('\n'));
  const config = loaded.config;
  const chatConfig = { ...config.chat!, ...(over.timeoutMs ? { timeoutMs: over.timeoutMs } : {}) };
  const db = await openSqlite(':memory:');
  await migrate(db);
  await migrateChat(db);
  const log: string[] = [];
  const fake = createFakeAdapter(SCRIPT);
  const context = parseChatContext(CONTEXT);
  if (typeof context === 'string') throw new Error(context);
  const chat = createChat({
    config: chatConfig, secret: config.secret, db, prompt: '# GENERATED BY AZ — test\nYou answer about Studio.\n', context, adapter: fake,
    log: (l) => log.push(l), ...(over.timing ? { timing: over.timing } : {}),
  });
  const app = createApp({
    config, store: createStore(db, config.secret), mailer: { send: async () => {} }, oidc: createOidc(fetch),
    log: (l) => log.push(l), chat,
  });
  const server = createServer((q, r) => { void app.handler(q, r); });
  const url = await listen(server);
  return {
    url, log, fake, chat: chatConfig, db,
    close: async () => { server.closeAllConnections(); server.close(); await db.close(); },
  };
}

/** A stream's events, read whole. */
async function events(r: Response): Promise<{ event: string; data: Record<string, unknown> }[]> {
  const reader = createSseReader();
  const all = [...reader.push(new Uint8Array(await r.arrayBuffer())), ...reader.end()];
  return all.map((e) => ({ event: e.event, data: JSON.parse(e.data) }));
}

const say = (text: string) => ({ role: 'visitor', text });
const ask = (c: ReturnType<typeof client>, messages: unknown[], extra: Record<string, unknown> = {}) =>
  c.post('/chat', { page: '/', messages, ...extra });

