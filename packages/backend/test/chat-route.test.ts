  assert.ok(loadConfig({ ...base, AZ_BACKEND_PUBLIC_URL: 'http://127.0.0.1:8787', AZ_CHAT_API: 'fake', AZ_CHAT_FAKE_FILE: './x.json' }, setup, 'Studio').ok);
  assert.deepEqual(problems({ ...good, AZ_CHAT_URL: 'http://localhost:11434/v1' }), []);
