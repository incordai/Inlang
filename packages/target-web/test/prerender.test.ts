/**
 * Pages are pre-rendered at build time and hydrated in the browser —
 * ASSUMPTIONS A6 (the SEO claim) and every "works without JS" claim.
 *
 * The site was client-rendered only: each page's HTML was an empty
 * <div id="root">, so with JS off — and for any crawler that does not run
 * it — every page was blank, and claims like "with JS off every FAQ answer
 * reads" were false. The project's build now renders every route to HTML
 * after the client build, and the browser hydrates that markup.
 *
 * These tests pin the emitted wiring; scripts/verify-build.mjs builds a real
 * site and checks the shipped HTML, and the browser gate loads it with JS off.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { compile, type Manifest } from '../../core/src/index.ts';
import { emit } from '../src/emit.ts';
import { WEB_EMITTERS } from '../../words/registry.ts';

const wordsDir = new URL('../../words/', import.meta.url);
const manifests = new Map<string, Manifest>();
for (const n of readdirSync(wordsDir)) {
  let raw: string;
  try { raw = readFileSync(new URL(`${n}/word.json`, wordsDir), 'utf8'); } catch { continue; }
  const m = JSON.parse(raw) as Manifest;
  manifests.set(m.name, m);
}
const files = (src: string) => {
  const r = compile(src, { manifests });
  assert.ok(r.spec, JSON.stringify(r.diagnostics));
  const out = emit(r.spec, { emitters: WEB_EMITTERS });
  return (p: string) => out.find((f) => f.path === p)?.content ?? null;
};
const PLAIN = 'az 1\nsite aurora\npage /\n  hero center\n    title "x"\npage /work\n';
const THREE_D = 'az 1\nsite aurora\npage /\n  hero split 3d\n    title "x"\n    poster ./p.webp\n    describe "A shoe"\n';

test('the build script is the pre-rendering build', () => {
  const file = files(PLAIN);
  const pkg = JSON.parse(file('package.json')!) as { scripts: Record<string, string> };
  assert.equal(pkg.scripts.build, 'node az-vite/build.mjs');
  assert.equal(pkg.scripts.dev, 'vite', 'CONTROL: development still serves from Vite');
});

test('the server entry renders one route with the same tree the browser hydrates', () => {
  const entry = files(PLAIN)('src/entry-server.tsx')!;
  assert.match(entry, /import \{ renderToString \} from "react-dom\/server";/);
  assert.match(entry, /export function render\(route: string\): string \{\n  return renderToString\(<StrictMode><App route=\{route\} \/><\/StrictMode>\);/);
});

test('build.mjs: client build, server build, then every page\'s HTML filled', () => {
  const build = files(PLAIN)('az-vite/build.mjs')!;
  assert.match(build, /^\/\* GENERATED BY AZ/);
  const client = build.indexOf('await build({ root');
  const server = build.indexOf('ssr: "src/entry-server.tsx"');
  const fill = build.indexOf('<div id="root"></div>');
  assert.ok(client > 0 && server > client && fill > server, 'client, then server, then the fill');
  assert.match(build, /envPrefix: "AZ_PUBLIC_"/, 'the server build sees the same public env as the page');
  assert.match(build, /React reported/, 'a React warning while rendering fails the build');
});

test('the browser hydrates pre-rendered markup, and renders from scratch only when there is none', () => {
  for (const main of [files(PLAIN)('src/main.tsx')!, files(THREE_D)('src/main.tsx')!]) {
    assert.match(main, /import \{ createRoot, hydrateRoot \} from "react-dom\/client";/);
    // The 3D entry renders synchronously when it must render at all.
    assert.match(main, /el\.firstElementChild\s*\? hydrateRoot\(el, app\)\s*: (flushSync\(\(\) => )?createRoot\(el\)/);
  }
});

test('the site is served from a domain root, and says so', () => {
  const vite = files(PLAIN)('vite.config.ts')!;
  // The old comment claimed a subdirectory deploy works; routes, asset URLs
  // and auth redirects are root-relative, so it never did.
  assert.doesNotMatch(vite, /subdirectory as well/);
  assert.match(vite, /served from a domain root/);
});
