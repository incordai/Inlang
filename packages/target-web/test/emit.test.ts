/**
 * Web target tests — including the two SECURITY tests VERIFICATION §5 says to
 * write in M1, not later.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { compile, type Manifest } from '../../core/src/index.ts';
import { emit, emitProject, escapeText, safeAssetPath, PathEscapeError } from '../src/emit.ts';
// A TEST may compose target + words, exactly as the CLI does. `deps.test.ts`
// forbids this in `src/` — that rule is about the shipped dependency arrow,
// and it scans src only. Without the real registry these tests would exercise
// nothing but the fallback renderer.
import { WEB_EMITTERS } from '../../words/registry.ts';

const wordsDir = new URL('../../words/', import.meta.url);
const manifests = new Map<string, Manifest>();
for (const n of readdirSync(wordsDir)) {
  let raw: string;
  try { raw = readFileSync(new URL(`${n}/word.json`, wordsDir), 'utf8'); } catch { continue; }
  const m = JSON.parse(raw) as Manifest;
  manifests.set(m.name, m);
}
const build = (src: string) =>
  emit(compile(src, { manifests }).spec!, { emitters: WEB_EMITTERS });
const fileNamed = (fs: { path: string; content: string }[], p: string) =>
  fs.find((f) => f.path === p)!;

const MINIMAL = 'az 1\nsite aurora\npage /\n  hero center\n    title "Built in the dark"\n';

test('a minimal file emits a runnable project', () => {
  const files = build(MINIMAL);
  for (const p of ['index.html', 'src/App.tsx', 'src/main.tsx', 'src/runtime.tsx', 'src/theme.css']) {
    assert.ok(files.some((f) => f.path === p), `missing ${p}`);
  }
});

test('every emitted file carries the GENERATED header — ARCHITECTURE §7', () => {
  for (const f of build(MINIMAL)) {
    if (f.path.endsWith('.html')) continue;   // html uses its own doctype
    if (f.path === 'package.json') {
      // JSON takes no comment, so §7's statement rides as data instead.
      assert.match(f.content, /"_generated": "BY AZ/, 'package.json has no marker');
      continue;
    }
    assert.match(f.content, /^\/\* GENERATED BY AZ/, `${f.path} has no header`);
  }
});

/* ---------------- SECURITY, VERIFICATION §5 ---------------- */

test('SECURITY: user content cannot break out of emitted code', () => {
  // The fixture VERIFICATION §5 names: a title containing </script>.
  const src = 'az 1\nsite a\npage /\n  hero center\n    title "</script><script>alert(1)</script>"\n';
  const app = fileNamed(build(src), 'src/App.tsx').content;
  assert.ok(!app.includes('</script>'), 'raw </script> reached the output');
  assert.ok(!app.includes('<script>'), 'raw <script> reached the output');
  assert.ok(app.includes('\u003c'), 'the angle bracket must be escaped');
});

test('SECURITY: a title cannot terminate the string literal', () => {
  const src = 'az 1\nsite a\npage /\n  hero center\n    title "he said \\"hi\\" then"\n';
  const app = fileNamed(build(src), 'src/App.tsx').content;
  // Every quote inside the value must be escaped, so the literal stays intact.
  const titleLine = app.split('\n').find((l) => l.includes('title'))!;
  assert.ok(!/[^\]"[^,}\s]/.test(titleLine.replace(/^\s*/, '')) || titleLine.includes('\u0022'));
});

test('CONTROL: escapeText leaves ordinary text readable', () => {
  // Without this, escaping everything to nothing would pass the tests above.
  assert.equal(escapeText('Built in the dark'), 'Built in the dark');
});

test('SECURITY: a path cannot escape the project', () => {
  assert.throws(() => safeAssetPath('../../../etc/passwd'), PathEscapeError);
  assert.throws(() => safeAssetPath('/etc/passwd'), PathEscapeError);
  assert.throws(() => safeAssetPath('C:/Windows/system32'), PathEscapeError);
  assert.throws(() => safeAssetPath('./a/../../../../etc/passwd'), PathEscapeError);
});

test('CONTROL: a legitimate asset path resolves', () => {
  assert.equal(safeAssetPath('./assets/shoe.glb'), 'assets/shoe.glb');
  assert.equal(safeAssetPath('assets/nested/../shoe.glb'), 'assets/shoe.glb');
});

test('emitProject lists each referenced asset once, sorted, and links it from the root', () => {
  const src = 'az 1\nsite aurora\n  nav bar\n    logo ./assets/z-logo.svg\n' +
    '  footer minimal\n    logo ./assets/z-logo.svg\n' +
    'page /\n  hero center\n    title "x"\n' +
    'page /work\n  cta split\n    title "y"\n    media ./assets/a-bench.webp\n';
  const r = compile(src, { manifests });
  assert.ok(r.spec, JSON.stringify(r.diagnostics));
  const { files, assets } = emitProject(r.spec, { emitters: WEB_EMITTERS });
  assert.deepEqual(assets, ['assets/a-bench.webp', 'assets/z-logo.svg']);
  const app = fileNamed(files, 'src/App.tsx').content;
  assert.match(app, /"\/assets\/z-logo\.svg"/);
  assert.doesNotMatch(app, /"\.\/assets\//, 'the author path must not reach the page unresolved');
});

test('CONTROL: emit() returns the same files as emitProject()', () => {
  const r = compile(MINIMAL, { manifests });
  assert.ok(r.spec);
  assert.deepEqual(emit(r.spec, { emitters: WEB_EMITTERS }),
    emitProject(r.spec, { emitters: WEB_EMITTERS }).files);
});

test('theme-spec §3.3: pages carry colour references, the stylesheet carries colours', () => {
  const files = build(MINIMAL);
  const app = fileNamed(files, 'src/App.tsx').content;
  assert.match(app, /var\(--az-color-/);
  assert.doesNotMatch(app, /hsl\(|rgb\(|#[0-9a-fA-F]{3,8}\b/, 'no colour literal may reach a page');
  const css = fileNamed(files, 'src/theme.css').content;
  assert.match(css, /--az-color-accent: hsl\(/);
  assert.match(css, /@media \(prefers-color-scheme: light\)/, 'midnight is dark by default');
  assert.match(fileNamed(files, 'index.html').content, /<meta name="color-scheme" content="light dark"/);
});

test('every page is its own HTML entry, so a static host serves each route', () => {
  const files = build('az 1\nsite aurora\npage /\n  hero center\n    title "x"\npage /work\npage /studio/team\n');
  const html = files.map((f) => f.path).filter((p) => p.endsWith('.html')).sort();
  assert.deepEqual(html, ['index.html', 'studio/team/index.html', 'work/index.html']);
  const vite = fileNamed(files, 'vite.config.ts').content;
  assert.match(vite, /"studio\/team": "studio\/team\/index\.html"/);
  assert.match(vite, /"index": "index\.html"/);
  const app = fileNamed(files, 'src/App.tsx').content;
  assert.match(app, /export default function App\(\{ route \}/, 'App renders one route, not every page');
});

test('SECURITY: a route cannot place an HTML file outside the project', () => {
  const r = compile('az 1\nsite aurora\npage /\n', { manifests });
  assert.ok(r.spec);
  const spec = { ...r.spec, pages: [...r.spec.pages, { route: '/../../escape', blocks: [] }] };
  assert.throws(() => emit(spec, { emitters: WEB_EMITTERS }), PathEscapeError);
});

/* ---------------- determinism, CONVENTIONS §6 ---------------- */

test('DETERMINISM: two emits are byte-identical', () => {
  const a = build(MINIMAL).map((f) => f.path + '\n' + f.content).join('\n');
  const b = build(MINIMAL).map((f) => f.path + '\n' + f.content).join('\n');
  assert.equal(a, b);
});

test('CONTROL: a changed source changes the output', () => {
  const a = build(MINIMAL).map((f) => f.content).join('');
  const b = build(MINIMAL.replace('Built in the dark', 'Made to last')).map((f) => f.content).join('');
  assert.notEqual(a, b);
});

test('no timestamps or random ids leak into output', () => {
  const all = build(MINIMAL).map((f) => f.content).join('\n');
  assert.ok(!/\d{4}-\d{2}-\d{2}T\d{2}:/.test(all), 'an ISO timestamp leaked');
  assert.ok(!/[0-9a-f]{8}-[0-9a-f]{4}-/.test(all), 'a uuid leaked');
});

test('files are emitted in a stable sorted order', () => {
  const paths = build(MINIMAL).map((f) => f.path);
  assert.deepEqual(paths, [...paths].sort());
});

test('site-level blocks are inherited into every page', () => {
  const src = 'az 1\nsite a\n  nav bar\npage /\n  hero center\n    title "Hi"\npage /two\n  text prose\n';
  const app = fileNamed(build(src), 'src/App.tsx').content;
  // `word="nav"` was a prop of the old generic Block component, and a bare
  // `az-nav` was the fallback's class before nav had an emitter. The probe
  // reads what the output actually carries now; the assertion is unchanged.
  const navCount = (app.match(/"az-nav az-nav--/g) ?? []).length;
  assert.equal(navCount, 2, 'nav must appear on both pages — nav-spec §8');
});

test('CONTROL: a nav declared on ONE page appears once, not on both', () => {
  // Without this, a build that emitted `az-nav` twice for an unrelated reason
  // would satisfy the test above.
  const src = 'az 1\nsite a\npage /\n  nav bar\npage /two\n  text prose\n';
  const app = fileNamed(build(src), 'src/App.tsx').content;
  assert.equal((app.match(/"az-nav az-nav--/g) ?? []).length, 1);
});
