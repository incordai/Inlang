/**
 * AZ.md — the generated project's map (azmd.ts). It is read instead of the
 * code, so it must be present, deterministic, complete for every page and
 * block, and free of anything secret.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { compile, type Manifest } from '../../core/src/index.ts';
import { emitProject } from '../src/emit.ts';
import { WEB_EMITTERS } from '../../words/registry.ts';
import { DEFAULT_THEME_NAME, colourChoicesMd } from '../../core/src/colour.ts';
import { ACCENT_HUES, PATTERN_SHAPE_NAMES, THEME_NAMES } from '../../core/src/link.ts';
import { ACCENT_PAIRS } from '../../core/src/accent-pairs.ts';

const wordsDir = new URL('../../words/', import.meta.url);
const manifests = new Map<string, Manifest>();
for (const n of readdirSync(wordsDir)) {
  let raw: string;
  try { raw = readFileSync(new URL(`${n}/word.json`, wordsDir), 'utf8'); } catch { continue; }
  const m = JSON.parse(raw) as Manifest;
  manifests.set(m.name, m);
}
const map = (src: string): string => {
  const { spec } = compile(src, { manifests });
  assert.ok(spec, 'fixture compiles');
  const file = emitProject(spec, { emitters: WEB_EMITTERS }).files.find((f) => f.path === 'AZ.md');
  assert.ok(file, 'AZ.md is emitted');
  return file.content;
};

const PLAIN = 'az 1\nsite aurora\npage /\n  hero center\n    title "Built in the dark"\n';

const FULL = `az 1

site studio
  auth
    adapter azbackend
    protect /account
  backend
    database sqlite
    email smtp

  nav bar
    link "Work" /work

page /
  hero center
    title "The studio"

page /login
  auth login
    redirect /account
    alt "Create an account" /signup

page /account/orders
  text
    title "Your orders"
    body  "None yet."
`;

test('AZ.md opens with the generated marker and is deterministic', () => {
  const a = map(FULL);
  assert.match(a, /^<!-- GENERATED BY AZ — .* -->\n/);
  assert.equal(map(FULL), a, 'two emits of one source differ');
});

test('AZ.md maps every route to its file and every block to its classes', () => {
  const md = map(FULL);
  assert.ok(md.includes('| `/` | `index.html` | nav bar · hero center |'), md);
  assert.ok(md.includes('| `/login` | `login/index.html` | nav bar · auth login |'), md);
  assert.ok(md.includes('| `/account/orders` | `account/orders/index.html` | nav bar · text prose |'), md);
  assert.match(md, /- `\/` · hero center — `header\.az-hero\.az-hero--center\.az-s-[a-z0-9]+`/);
  assert.match(md, /- `\/login` · auth login — `section\.az-auth\.az-auth--login\.az-s-[a-z0-9]+`/);
});

test('AZ.md names the runtimes, env keys and server only when the site uses them', () => {
  const full = map(FULL);
  assert.ok(full.includes('`src/az-auth/`'), 'auth runtime');
  assert.ok(full.includes('`AZ_PUBLIC_BACKEND_URL`'), 'public key');
  assert.ok(full.includes('Protected routes (sign-in required): `/account`.'), 'protected routes');
  assert.ok(full.includes('`server/`'), 'backend');
  // The server gets its own section: what it is and what each file does.
  assert.ok(full.includes('\n## Server\n'), 'server section');
  for (const f of ['server/src/main.ts', 'server/src/app.ts', 'server/.env.example', 'server/README.md']) {
    assert.ok(full.includes(`\`${f}\``), f);
  }

  const plain = map(PLAIN);
  assert.ok(plain.includes('`src/az/`'), 'the behaviour runtime is always shipped');
  assert.ok(!plain.includes('src/az-auth'), 'no auth runtime without auth');
  assert.ok(!plain.includes('src/az3d'), 'no 3D runtime without 3D');
  assert.ok(!plain.includes('server/'), 'no server without a backend');
  assert.ok(!plain.includes('## Server'), 'no server section without a backend');
  assert.ok(plain.includes('No public keys are needed.'));
});

test('SECURITY: AZ.md lists key names, never values or server secrets', () => {
  const md = map(FULL);
  assert.ok(!/AZ_SESSION_SECRET|AZ_DATABASE_URL|AZ_SMTP_PASSWORD|AZ_EMAIL_API_KEY|=\S/.test(md), 'a secret name or an assignment reached the map');
});

/* ---- colour first (PRD §6.1a) ------------------------------------------- */

const COLOURED = (theme: string, settings: string) =>
  `az 1\nsite aurora\n  theme ${theme}\n${settings}page /\n  hero center\n    title "Built in the dark"\n`;

/** The `## Colour (change this first)` section, up to the next heading. */
const colourSection = (md: string): string => {
  const at = md.indexOf('\n## Colour (change this first)\n');
  assert.ok(at >= 0, 'AZ.md has a colour section');
  const end = md.indexOf('\n## ', at + 1);
  return md.slice(at, end < 0 ? undefined : end);
};

test('AZ.md opens with the colour section: before every other section, with the current theme, accent and pattern', () => {
  const md = map(COLOURED('signal', '    accent violet blue\n    pattern glow left\n'));
  assert.equal(md.indexOf('\n## Colour (change this first)\n'), md.indexOf('\n## '), 'colour is the first section');
  const c = colourSection(md);
  assert.ok(c.includes('Now: theme `signal`. Accent: `violet blue` — a gradient pair'), c);
  assert.ok(c.includes('Pattern: `glow left`'), c);
  assert.ok(c.includes('```az\nsite aurora\n  theme signal\n    accent violet blue\n    pattern glow left\n```'), c);
  assert.ok(c.includes('no hex'), 'colours come only from the theme');
  assert.ok(c.includes(`without a \`theme\` line the site gets \`${DEFAULT_THEME_NAME}\``), c);
});

test("AZ.md's colour section lists the legal values from the shared tables, with its own theme's pairs", () => {
  const c = colourSection(map(COLOURED('signal', '')));
  assert.ok(c.includes(colourChoicesMd('signal').join('\n')), c);
  for (const [t, text] of Object.entries(THEME_NAMES)) assert.ok(c.includes(`  - \`${t}\` — ${text}`), t);
  for (const h of Object.keys(ACCENT_HUES)) {
    const partners = ACCENT_PAIRS.signal[h];
    assert.ok(c.includes(`  - \`${h}\` with ${partners.length ? partners.join(', ') : 'no hue'}\n`), h);
  }
  for (const [s, text] of Object.entries(PATTERN_SHAPE_NAMES)) assert.ok(c.includes(`  - \`${s}\` — ${text}`), s);
});

test("AZ.md's colour section changes when the theme, accent or pattern changes", () => {
  const signal = colourSection(map(COLOURED('signal', '')));
  const paper = colourSection(map(COLOURED('paper', '    accent teal\n')));
  assert.notEqual(paper, signal);
  assert.ok(paper.includes('Now: theme `paper`. Accent: `teal` — regenerated from its hue ramp'), paper);
  assert.ok(paper.includes('```az\nsite aurora\n  theme paper\n    accent teal\n```'), paper);
  // Pairs are per theme: paper allows green with amber, signal refuses it.
  assert.ok(paper.includes('  - `green` with teal, amber\n'), paper);
  assert.ok(signal.includes('  - `green` with teal\n'), signal);
  assert.ok(signal.includes("Accent: the theme's own. Pattern: none."), signal);
});

const CHAT_SITE = `az 1
site lantern
  auth
    adapter azbackend
  backend
    database sqlite
    email    smtp
    model    default
page /
  hero center
    title "Lantern"
  chat panel
    show  pricing faq cta
    allow anyone
page /pricing
  pricing cards
    title    "Plans"
    currency usd
    plan "Home"
      monthly 9
      cta "Start" /
page /help
  chat panel
page /login
  auth login
    alt "Back" /
`;

test('AZ.md describes a site\'s chats: each page\'s panel, what its answers show and quote, and the chat files', () => {
  const md = map(CHAT_SITE);
  const section = md.slice(md.indexOf('## Chat'));
  assert.ok(md.includes('## Chat'), md);
  assert.ok(section.includes('| `/` | anyone | 20 | pricing, faq, cta | `/pricing#0` |'), section);
  assert.ok(section.includes('| `/help` | signed-in visitors | 20 | text only | — |'), section);
  for (const f of ['src/az/chat.ts', 'server/chat/prompt-<n>.txt', 'server/chat/context.json', 'server/src/chat-answer.ts', 'az backend probe server']) {
    assert.ok(section.includes(f), f);
  }
  // Nothing secret, and no provider: the keys are named, never valued.
  assert.ok(!/sk-|Bearer /.test(section));
  // CONTROL: a site without a chat has no chat section.
  assert.ok(!map(PLAIN).includes('## Chat'));
});

test('AZ.md lists each chat\'s answer presets — the author\'s and those show auto made, how to replace them — and the suggested questions that answer without the model (§19.17)', () => {
  const source = CHAT_SITE.replace(/    show (.*)\n/, '    show $1 auto\n    ask "Plans?" use pricing\n    answer talk\n      keywords "contact" "talk"\n      cta "Talk to us" /\n');
  const section = map(source).slice(map(source).indexOf('## Chat'));
  assert.match(section, /Answer presets on `\/`/);
  assert.match(section, /- `talk` `cta "Talk to us" \/` — matched by "contact" "talk"/);
  assert.match(section, /- `pricing` `show pricing \/pricing` \(made by `show auto`: the pricing block[^)]*; write `answer pricing` to replace it\) — matched by /);
  assert.match(section, /- suggested "Plans\?" answers with `use pricing`, without the model/);
  // CONTROL: a chat with neither lists none.
  assert.ok(!map(CHAT_SITE).includes('Answer presets on'));
});

test('AZ.md for a site without a theme line names the default and the line to add', () => {
  const c = colourSection(map(PLAIN));
  assert.ok(c.includes(`Now: theme \`${DEFAULT_THEME_NAME}\`.`), c);
  assert.ok(c.includes(`\`\`\`az\nsite aurora\n  theme ${DEFAULT_THEME_NAME}\n\`\`\``), c);
});
