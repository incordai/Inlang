/**
 * @az module chat-library
 * Purpose: the chat's page shell as an app draws it without a build — the chat word's own panel, its templates and their stylesheet, for one theme.
 * Spec: docs/chat-block-spec.md §22.3
 * Exports: chatLibrarySet, ChatLibrarySet, LIBRARY_ROOT, LIBRARY_WINDOW
 * Edit guide: the shell is exactly what the chat word emits for a page and the target compiles for it — no styling of its own here
 *   but the page-level rules a site's theme.css has, scoped to the library's root; deterministic.
 * Tests: scripts/lib/chat-themes.test.mjs
 */

/**
 * An `az build` page ships the chat as a pre-rendered shell whose hidden
 * templates the page runtime fills (chat-block-spec §5.4). An app has no
 * build, so the chat renderer (packages/chat-render) carries the same shell
 * per theme, generated here from the same emitters and stylesheet compiler a
 * site's build runs: the chat word's panel for a chat that shows every
 * component, every class it uses, and the page-level rules a site's
 * theme.css gives it — the reset, `hidden`, the reduced-motion net, the
 * theme's colour schemes and the map popup's colours — scoped to the
 * library's root element, so they never touch the host app's own page.
 * scripts/gen-chat-themes.mjs writes one module and one stylesheet per theme.
 */

import type { EmittedNode } from '../../core/src/emit-contract.ts';
import type { Spec } from '../../core/src/index.ts';
import { scopedSchemeCss, type Scheme } from '../../theme/src/index.ts';
import { mapCss } from './chat.ts';
import { namedTheme, themeFor } from './emit.ts';
import { compileStyles } from './stylesheet.ts';
import { emitPages, type EmitterMap } from './tree.ts';

/** The attribute the renderer's root element carries, beside `data-az-theme="<name>"`. */
export const LIBRARY_ROOT = 'data-az-chat-root';

/** The attribute a whole window's root carries beside it (`<AzChat>`): the window fills the host's box. */
export const LIBRARY_WINDOW = 'data-az-chat-window';

export interface ChatLibrarySet {
  /** The theme's name, as `data-az-theme` names it. */
  readonly theme: string;
  /** The chat block as its page renders it, every style a class. */
  readonly shell: EmittedNode;
  /** Every rule the shell needs, scoped to the library's root for this theme. */
  readonly css: string;
}

const walk = (n: EmittedNode | string): EmittedNode[] => (typeof n === 'string' ? [] : [n, ...(n.children ?? []).flatMap(walk)]);

/** An author's component has no place in a chat's shell: the fixture holds none. */
const noComponents = (path: string): string => {
  throw new Error(`chat library: the fixture names a component (${path}), which a shell never holds`);
};

/**
 * The shell of the chat on `spec`'s first page and its stylesheet. `spec`
 * is a fixture site whose chat shows every component and whose pages
 * declare a destination of each kind, so every template is there.
 */
export function chatLibrarySet(spec: Spec, emitters: EmitterMap): ChatLibrarySet {
  const named = namedTheme(spec);
  const theme = themeFor(named, spec.site.fonts, false);
  const pages = emitPages(spec, theme, emitters, (path) => `/${path}`, noComponents);
  const chat = pages.flatMap((p) => p.nodes.flatMap(walk)).find((n) => n.attrs?.['data-az-chat'] !== undefined);
  if (!chat) throw new Error('chat library: the fixture shows no chat');
  const styled = compileStyles([chat], (nodes, rewrite) => nodes.map(rewrite), theme.breakpoint);
  const root = `[${LIBRARY_ROOT}][data-az-theme="${named.name}"]`;
  // The page-level rules weigh what a site's do (an element, or nothing): inside :where() the scope adds nothing, so a
  // generated class still wins over the reset, exactly as on a site's page.
  const at = `:where(${root})`;
  const win = `${root}[${LIBRARY_WINDOW}]`;
  const base: Scheme = named.defaultScheme ?? 'light';
  const other: Scheme = base === 'light' ? 'dark' : 'light';
  const indent = (css: string) => css.trimEnd().split('\n').map((l) => `  ${l}`).join('\n');
  const scoped = (css: string) => css.replace(/^(\s*)(\.az-chat-map-stage)/gm, `$1${at} $2`);
  const css = `/* The chat renderer's ${named.name} theme (chat-block-spec §22.3): generated by scripts/gen-chat-themes.mjs from the chat word
   and the target's stylesheet compiler — the same classes an az site's page has. Every page-level rule is scoped to the
   renderer's root, so the host page is never styled. */
${at}, ${at} *, ${at} *::before, ${at} *::after { box-sizing: border-box; }
${at} { font-family: ${theme.type.body}; color: var(--az-color-text); }
${at} button, ${at} input, ${at} select, ${at} textarea { font: inherit; }
${at} ul, ${at} ol { margin: 0; padding: 0; }
${at} img, ${at} video, ${at} canvas { max-width: 100%; height: auto; display: block; }
${at} a { color: inherit; }
${at} [hidden]:not([hidden="until-found"]) { display: none !important; }
@media (prefers-reduced-motion: reduce) {
  ${at} *, ${at} *::before, ${at} *::after {
    animation: none !important;
    transition-property: opacity !important;
    transition-duration: ${theme.motion.reduced}ms !important;
    scroll-behavior: auto !important;
  }
}

/* ${named.name}: ${base} by default, ${other} on request — theme-spec §3.2, on the renderer's root. */
${scopedSchemeCss(named, base, root).trimEnd()}
@media (prefers-color-scheme: ${other}) {
${indent(scopedSchemeCss(named, other, `${root}:not([data-scheme="${base}"])`))}
}
${scopedSchemeCss(named, other, `${root}[data-scheme="${other}"]`).trimEnd()}
${scoped(mapCss(theme)).trimEnd()}

/* An app's whole window (<AzChat>, chat-block-spec §22.5): the host's box is its size — the section and its panel fill it,
   and the transcript scrolls in the height the rest leaves. Three attributes and a class outweigh the section's own classes. */
${win} { display: flex; flex-direction: column; block-size: 100%; min-block-size: 0; }
${win} > .az-chat { display: flex; flex: 1 1 auto; flex-direction: column; min-block-size: 0; padding: 0; }
${win} .az-chat-panel { display: flex; flex: 1 1 auto; flex-direction: column; min-block-size: 0; max-width: none; }
${win} .az-chat-transcript { flex: 1 1 auto; min-block-size: 0; max-block-size: none; }

/* The chat word's own classes, compiled as a site's build compiles them. */
${styled.css}`;
  return { theme: named.name, shell: styled.value[0], css };
}
