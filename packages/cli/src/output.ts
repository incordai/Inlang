/**
 * @az module output
 * Purpose: writes a build into its folder safely: generated-file manifest, stale removal, symlink refusal.
 * Spec: docs/ARCHITECTURE.md §7
 * Exports: writeOutput, writeProblem, writeOnce, MANIFEST
 * Edit guide: never overwrite or delete a file az did not generate.
 * Tests: packages/cli/test/hardening.test.ts
 */

/**
 * Writing a build into its output folder, safely.
 *
 * Four rules, each a finding from the core review:
 *   1. Every target stays inside the output folder. A path the target emits
 *      is checked after resolving, so a route like `/C:/x` on Windows cannot
 *      write elsewhere, and no existing symbolic link on the way is followed —
 *      `public/assets -> /elsewhere` would otherwise carry a copy out.
 *   2. A file az did not generate is never overwritten. `--out .` in a
 *      project folder used to replace the project's own package.json.
 *   3. A file az generated last time and not this time is removed, so the
 *      output depends on the current source, not on build history (an asset
 *      dropped from the .az no longer ships). Nothing else is ever deleted.
 *   4. The list of generated files is the manifest, written last.
 */

import {
  closeSync, copyFileSync, existsSync, lstatSync, mkdirSync, openSync, readFileSync, readdirSync, realpathSync, rmdirSync,
  unlinkSync, writeFileSync,
} from 'node:fs';
import { dirname, isAbsolute, join, relative, sep } from 'node:path';

/** The manifest of generated files, at the output root. */
export const MANIFEST = '.az-manifest.json';

/** The first line every generated source carries (ARCHITECTURE §7). */
const GENERATED_HEADER = '/* GENERATED BY AZ';

/** One file of a build: text to write, or a project file to copy. */
export type Planned =
  | { readonly path: string; readonly content: string }
  | { readonly path: string; readonly copyFrom: string };

export type WriteResult =
  | { readonly ok: true; readonly written: number; readonly removed: string[] }
  | { readonly ok: false; readonly problems: string[] };

const inside = (root: string, target: string): boolean => {
  const rel = relative(root, target);
  return rel !== '' && !rel.startsWith('..') && !isAbsolute(rel);
};

/** The generated paths recorded by the previous build, or null for none. */
function previousManifest(root: string): Set<string> | null {
  const file = join(root, MANIFEST);
  if (!existsSync(file)) return null;
  try {
    const parsed = JSON.parse(readFileSync(file, 'utf8')) as { files?: unknown };
    return Array.isArray(parsed.files) ? new Set(parsed.files.filter((f): f is string => typeof f === 'string')) : null;
  } catch {
    return null;
  }
}

/**
 * An output folder written before manifests existed: its App carries the
 * generated header. Its files are az's, so the first build with a manifest
 * may replace them; any other folder without a manifest is treated as the
 * author's.
 */
function isEarlierOutput(root: string): boolean {
  const app = join(root, 'src/App.tsx');
  return existsSync(app) && readFileSync(app, 'utf8').startsWith(GENERATED_HEADER);
}

/**
 * Why `rel` may not be written under `root` (a real, resolved path), or null
 * when it may: it must stay inside, and no existing part of it may be a link.
 */
export function writeProblem(root: string, rel: string): string | null {
  const target = join(root, rel);
  if (isAbsolute(rel) || !inside(root, target)) return `'${rel}' would be written outside the output folder`;
  let at = root;
  for (const segment of relative(root, target).split(sep)) {
    at = join(at, segment);
    if (!existsSync(at) && !isSymlink(at)) return null;
    if (isSymlink(at)) return `'${relative(root, at)}' is a symbolic link — az does not write through links`;
  }
  return null;
}

/**
 * Create `file` with `text` only when nothing is at that path, in one step:
 * the exclusive create (`wx`) is the check, so nothing can appear between a
 * check and the write, and a link at the path — even one pointing nowhere —
 * is never written through. False when something was already there.
 */
export function writeOnce(file: string, text: string, mode = 0o666): boolean {
  let fd: number;
  try {
    fd = openSync(file, 'wx', mode);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'EEXIST') return false;
    throw e;
  }
  try {
    writeFileSync(fd, text, 'utf8');
  } finally {
    closeSync(fd);
  }
  return true;
}

function isSymlink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

/**
 * Whether `target` already holds exactly `file`'s bytes; null when nothing
 * is there. Read, not checked first: a file that goes between a check and
 * the read is "nothing there", never a crash.
 */
const sameBytes = (target: string, file: Planned): boolean | null => {
  let now: Buffer;
  try {
    now = readFileSync(target);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw e;
  }
  return 'content' in file ? now.equals(Buffer.from(file.content, 'utf8')) : now.equals(readFileSync(file.copyFrom));
};

/** Remove now-empty folders from `dir` up to (not including) `root`. */
function pruneEmpty(root: string, dir: string): void {
  let at = dir;
  while (inside(root, at) && existsSync(at) && readdirSync(at).length === 0) {
    rmdirSync(at);
    at = dirname(at);
  }
}

/**
 * Write `files` into `outDir` under the rules above. Nothing is written
 * unless every file may be: the checks all run first.
 */
export function writeOutput(outDir: string, files: readonly Planned[]): WriteResult {
  mkdirSync(outDir, { recursive: true });
  const root = realpathSync(outDir);
  const before = previousManifest(root);
  const owned = (rel: string) => before ? before.has(rel) : isEarlierOutput(root);

  const problems: string[] = [];
  for (const file of files) {
    const reason = writeProblem(root, file.path);
    if (reason) { problems.push(`output: ${reason}`); continue; }
    const target = join(root, file.path);
    if (!owned(file.path) && sameBytes(target, file) === false) {
      problems.push(`output: '${file.path}' exists and az did not generate it — build into an empty folder, or move it`);
    }
  }
  if (problems.length > 0) return { ok: false, problems };

  let written = 0;
  for (const file of files) {
    const target = join(root, file.path);
    if (sameBytes(target, file) === true) continue;
    mkdirSync(dirname(target), { recursive: true });
    if ('content' in file) writeFileSync(target, file.content, 'utf8');
    else copyFileSync(file.copyFrom, target);
    written++;
  }

  const now = new Set(files.map((f) => f.path));
  const removed: string[] = [];
  for (const rel of [...(before ?? [])].sort()) {
    if (now.has(rel) || writeProblem(root, rel)) continue;
    const target = join(root, rel);
    if (!existsSync(target) || isSymlink(target) || !lstatSync(target).isFile()) continue;
    unlinkSync(target);
    removed.push(rel);
    pruneEmpty(root, dirname(target));
  }

  writeFileSync(join(root, MANIFEST), JSON.stringify({
    _generated: 'BY AZ — the files az wrote here; it removes those it no longer writes',
    files: [...now].sort(),
  }, null, 2) + '\n', 'utf8');
  return { ok: true, written, removed };
}
