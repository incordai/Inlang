/**
 * Regenerate packages/core/src/currencies.ts — the currency codes a `money`
 * field accepts, and each one's minor-unit digits (data-spec §4.3).
 *
 *     node scripts/gen-currencies.mjs
 *
 * The source is the Unicode CLDR data compiled into Node's ICU, read ONCE
 * here and committed. Reading it at build time instead would make two builds
 * differ by Node version (data-spec §4.3), so the table is data in the repo.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../packages/core/src/currencies.ts', import.meta.url));
const digits = (code) => new Intl.NumberFormat('en', { style: 'currency', currency: code })
  .resolvedOptions().maximumFractionDigits;
const codes = Intl.supportedValuesOf('currency').map((c) => c.toLowerCase()).sort();
const rows = codes.map((c) => `  ${c}: ${digits(c.toUpperCase())},`).join('\n');

writeFileSync(out, `/**
 * @az module currencies
 * Purpose: currency codes a money field accepts, with each one's minor-unit digits.
 * Spec: docs/data-spec.md §4.3
 * Exports: CURRENCY_DIGITS
 * Edit guide: regenerate with node scripts/gen-currencies.mjs — never edit by hand.
 * Tests: packages/core/test/data.test.ts
 */

/**
 * GENERATED by scripts/gen-currencies.mjs from the Unicode CLDR currency data
 * in Node's ICU (ICU ${process.versions.icu}, CLDR ${process.versions.cldr}): ${codes.length} codes.
 * Committed, so a build never depends on the Node version that runs it.
 * The value is the number of minor-unit digits: usd 2 (cents), jpy 0, bhd 3.
 */
export const CURRENCY_DIGITS: Readonly<Record<string, number>> = Object.freeze({
${rows}
});
`, 'utf8');
process.stdout.write(`wrote ${out} (${codes.length} codes)\n`);
