/**
 * Generates packages/core/src/accent-pairs.ts — which `theme accent <hue> <hue2>`
 * pairs each theme allows (theme-spec §13).
 *
 * The proof lives in the theme package (packages/theme/src/gradient.ts:
 * pairVerdict samples every rendering of every gradient in both schemes);
 * this script only runs it for every theme × hue × hue and writes the names
 * that passed. The output is names, no colours, so the linker in core can
 * refuse a pair with a source position (AZ1423) without importing the theme
 * (ARCHITECTURE §2). packages/theme/test/gradient.test.ts regenerates and
 * compares, so the table can never drift from the proof.
 *
 * A new theme joins by being added to THEMES and rerunning this script.
 *
 * Run: node scripts/gen-pairs.mjs
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { THEMES } from '../packages/theme/src/themes.ts';
import { pairTable } from '../packages/theme/src/gradient.ts';

/** The TypeScript source of accent-pairs.ts. */
export function pairsSource() {
  const lines = [
    '/**',
    ' * @az module accent-pairs',
    ' * Purpose: which `theme accent <hue> <hue2>` pairs each theme allows — names only, for the linker.',
    ' * Spec: docs/theme-spec.md §13 · docs/GRAMMAR.md §4.4 (theme settings)',
    ' * Exports: ACCENT_PAIRS',
    ' * Edit guide: GENERATED by scripts/gen-pairs.mjs from the theme package\'s proof — change the rule there and rerun.',
    ' * Tests: packages/theme/test/gradient.test.ts, packages/core/test/theme-settings.test.ts',
    ' */',
    '',
    '/** Theme → hue → the hues it pairs with, in ramp order. Symmetric: a pair holds either way round. */',
    'export const ACCENT_PAIRS: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = {',
  ];
  for (const [name, theme] of Object.entries(THEMES)) {
    lines.push(`  ${name}: {`);
    for (const [hue, partners] of Object.entries(pairTable(theme))) {
      lines.push(`    ${hue}: [${partners.map((p) => `'${p}'`).join(', ')}],`);
    }
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = fileURLToPath(new URL('../packages/core/src/accent-pairs.ts', import.meta.url));
  writeFileSync(target, pairsSource(), 'utf8');
  console.log(`wrote ${target}`);
}
