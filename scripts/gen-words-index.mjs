/**
 * Generates docs/WORDS.md — the word index for people and AI tools — and the
 * words catalogue table in the root README.md.
 *
 * Both are read instead of eleven folders: every word, variant, modifier and
 * key with its ≤60-character info line (word.json, the text `az explain`
 * prints), the preview that shows each variant, and the file to edit for each
 * concern — copy, style tokens, layout, behaviour, validation — taken from
 * the emitter's `@az` header (packages/core/test/headers.test.ts keeps that
 * header true). Nothing here is written by hand, so nothing can drift:
 * packages/words/test/words-index.test.ts regenerates both and fails unless
 * the committed files equal a fresh run, byte for byte.
 *
 * The index opens with "Step 1: colour" (PRD §6.1a): the legal themes, hues,
 * pairs and patterns come from the compiler's own tables
 * (packages/core/src/colour.ts), the same text the generated AZ.md prints.
 *
 * Run: node scripts/gen-words-index.mjs
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_THEME_NAME, colourChoicesMd, themeLinesAz } from '../packages/core/src/colour.ts';
import { ACCENT_PAIRS } from '../packages/core/src/accent-pairs.ts';
import { PATTERN_ORIGIN_NAMES, PATTERN_SHAPE_NAMES } from '../packages/core/src/link.ts';

export const ROOT = fileURLToPath(new URL('../', import.meta.url));
const WORDS_DIR = 'packages/words';
export const INDEX_FILE = 'docs/WORDS.md';
export const README_FILE = 'README.md';
export const CATALOGUE_START = '<!-- words-catalogue:start (generated by scripts/gen-words-index.mjs — do not edit) -->';
export const CATALOGUE_END = '<!-- words-catalogue:end -->';

/** The reserved variant that renders nothing (GRAMMAR §5.2); thumbnails skip it. */
const RENDERS_NOTHING = 'none';

/** Every word folder (a directory holding a word.json), sorted, as { dir, manifest, readme, emitter, files }. */
export function loadWords(root = ROOT) {
  const base = join(root, WORDS_DIR);
  return readdirSync(base, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(base, e.name, 'word.json')))
    .map((e) => e.name)
    .sort()
    .map((dir) => {
      const at = (f) => join(base, dir, f);
      return {
        dir,
        manifest: JSON.parse(readFileSync(at('word.json'), 'utf8')),
        emitter: existsSync(at('emit.web.ts')) ? readFileSync(at('emit.web.ts'), 'utf8') : '',
        previewSource: existsSync(at('preview.az')) ? readFileSync(at('preview.az'), 'utf8') : '',
        files: readdirSync(join(base, dir)).sort(),
      };
    });
}

/** The fields of the emitter's leading `@az word` header (the same shape headers.test.ts parses). */
export function headerFields(src) {
  const m = /^\/\*\*\n \* @az (\S+) (\S+)\n([\s\S]*?)\n \*\/\n/.exec(src);
  if (!m) return {};
  const fields = {};
  let current = null;
  for (const raw of m[3].split('\n')) {
    const line = raw.replace(/^ \* ?/, '');
    const field = /^([A-Z][a-z]+(?: [a-z]+)?): (.*)$/.exec(line);
    if (field && !line.startsWith('  ')) { current = field[1]; fields[current] = field[2]; }
    else if (current) fields[current] += ` ${line.trim()}`;
  }
  return fields;
}

/** A value safe inside one markdown table cell: a backslash escaped first, so a `\|` in the value stays text, not an escaped pipe. */
const cell = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const code = (s) => `\`${s}\``;

/** The variant the word's preview.az line uses: the one written, else the manifest's first. */
function previewVariant(source, word, variants) {
  const line = source.split('\n').find((l) => new RegExp(`^\\s+${word}(\\s|$)`).test(l)) ?? '';
  return line.trim().split(/\s+/).slice(1).find((t) => variants.includes(t)) ?? variants[0];
}

/** Which preview shows a variant — the rule scripts/thumbnails.mjs and visual.mjs apply. */
function previewOf(w, variant, inPreview) {
  if (variant === RENDERS_NOTHING) return 'renders nothing; no thumbnail';
  if (w.files.includes(`preview.${variant}.az`)) return code(`preview.${variant}.az`);
  if (variant === inPreview) return code('preview.az');
  return `${code('preview.az')} with the variant swapped in`;
}

function propType(p) {
  const bits = [p.type];
  if (p.scope === 'site') bits.push('site level');
  if (p.required) bits.push('required');
  return bits.join(', ');
}

const valuesOf = (p) => (Array.isArray(p.values) ? p.values.map(code).join(' / ') : '');
const defaultOf = (p) => (p.default === undefined ? '' : code(p.default));

/** Key rows: props, slots and their nested props/slots, nav-style children, and `from` mappings. */
function keyRows(m) {
  const rows = [];
  const props = (prefix, ps) => {
    for (const [k, p] of Object.entries(ps ?? {})) {
      rows.push([code(prefix + k), propType(p), valuesOf(p), defaultOf(p), p.description]);
    }
  };
  const slots = (prefix, ss) => {
    for (const [k, s] of Object.entries(ss ?? {})) {
      const n = [s.min !== undefined ? `min ${s.min}` : '', s.max !== undefined ? `max ${s.max}` : ''].filter(Boolean).join(', ');
      rows.push([code(prefix + k), `child${n ? ` (${n})` : ''}`, '', '', s.description]);
      props(`${prefix}${k} › `, s.props);
      slots(`${prefix}${k} › `, s.slots);
    }
  };
  props('', m.props);
  slots('', m.slots);
  for (const c of m.children ?? []) {
    const max = m.limits?.[c]?.max;
    rows.push([code(c), `child${max !== undefined ? ` (max ${max})` : ''}`, '', '', m.descriptions?.children?.[c]]);
  }
  if (m.from) {
    rows.push([code('from'), `data table (fills ${code(m.from.slot)})`, '', '', m.from.description]);
    for (const [k, f] of Object.entries(m.from.map ?? {})) {
      rows.push([code(`from › ${k}`), `field: ${(f.types ?? []).join(' / ')}${f.required ? ', required' : ''}`, '', '', f.description]);
    }
  }
  return rows;
}

function codeRange(m) {
  const codes = (m.checks ?? []).map((c) => c.code).sort();
  if (!codes.length) return 'none';
  return codes.length === 1 ? code(codes[0]) : `${code(codes[0])}–${code(codes[codes.length - 1])} (${codes.length})`;
}

function table(head, rows) {
  return [
    `| ${head.join(' | ')} |`,
    `|${head.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
  ];
}

function wordSection(w) {
  const m = w.manifest;
  const h = headerFields(w.emitter);
  const name = m.name;
  const pkg = `../${WORDS_DIR}/${w.dir}`;
  const variants = m.variants ?? [];
  const inPreview = previewVariant(w.previewSource, name, variants);
  const previews = w.files.filter((f) => /^preview(\.[a-z]+)?\.az$/.test(f));
  const out = [
    `## \`${name}\``,
    '',
    `${m.description}`,
    '',
    `[README](${pkg}/README.md) · [spec](${name}-block-spec.md) · terms: \`az explain ${name}\``,
    '',
    '### Variants',
    '',
    ...table(['Variant', 'Info', 'Preview'], variants.map((v, i) => [
      code(v) + (i === 0 ? ' (default)' : ''), m.descriptions?.variants?.[v], previewOf(w, v, inPreview),
    ])),
    '',
  ];
  if ((m.modifiers ?? []).length) {
    out.push('### Modifiers', '', ...table(['Modifier', 'Info'],
      m.modifiers.map((v) => [code(v), m.descriptions?.modifiers?.[v]])), '');
  }
  out.push('### Keys', '', ...table(['Key', 'Kind', 'Values', 'Default', 'Info'], keyRows(m)), '');
  out.push('### Where to edit', '', ...table(['Concern', 'Edit'], [
    ['Copy', `the site's \`.az\` file (the keys above); worked examples: ${previews.map(code).join(', ')}`],
    ['Info lines, keys, values, bounds', `${code(`${WORDS_DIR}/${w.dir}/word.json`)} — \`description\`, \`descriptions\`, each key's \`description\``],
    ['Style tokens', `values: ${code('packages/theme/src/themes.ts')} (per theme), ${code('packages/theme/src/tokens.ts')} (scales); its own code reads ${(m.themeReads ?? []).map(code).join(', ')} (${code('themeReads')}, held to the code by ${code('pnpm lint')}; shared helpers and ${code('ctx.actions')} read their own)`],
    ['Style and layout', `${code(`${WORDS_DIR}/${w.dir}/emit.web.ts`)} — ${h.Styling ?? ''}`],
    ['Markup', `${code(`${WORDS_DIR}/${w.dir}/emit.web.ts`)} — ${h['Edit guide'] ?? ''}`],
    ['Behaviour', h.Behaviour ?? ''],
    ['Validation', `${code(`${WORDS_DIR}/${w.dir}/word.json`)} \`checks\`: ${codeRange(m)}`],
    ['Tests', (h.Tests ?? '').split(',').map((s) => s.trim()).filter(Boolean).map(code).join(', ')],
  ]), '');
  out.push(`Gate: \`pnpm verify\` · \`pnpm lint\` · \`pnpm gate words/${name}\` · \`pnpm thumbnails ${name} --verify\``, '');
  return out.join('\n');
}

/**
 * "Step 1: colour" — the authoring order and every legal colour value, from
 * the compiler's tables. The example is the default theme, its first hue and
 * that hue's first partner, and the first shape that paints, so it is always
 * a pair the compiler allows.
 */
export function colourStepSource() {
  const [hue, partners] = Object.entries(ACCENT_PAIRS[DEFAULT_THEME_NAME]).find(([, p]) => p.length > 0);
  const shape = Object.keys(PATTERN_SHAPE_NAMES).find((s) => s !== 'none');
  const example = themeLinesAz({
    site: 'aurora', theme: DEFAULT_THEME_NAME, accent: hue, accent2: partners[0],
    pattern: `${shape} ${Object.keys(PATTERN_ORIGIN_NAMES)[0]}`,
  });
  return [
    '## Step 1: colour',
    '',
    'Every site starts with colour, before any section is written (PRD §6.1a): pick the',
    'theme, the accent (one hue, or an allowed pair for a gradient) and the pattern from the',
    "user's brand or mood, and confirm them with the user. Then the frame (`width`, `font`),",
    'then the sections — the words below. Colours come only from the theme: there is no hex',
    'value or colour name to write, in a `.az` file or in a word (`pnpm lint`).',
    '',
    '```az',
    ...example,
    '```',
    '',
    '`az explain theme` lists the themes and `az explain theme accent` the pairs. The legal',
    "values, from the compiler's own tables:",
    '',
    ...colourChoicesMd(null),
    '',
  ];
}

/** docs/WORDS.md, in full. */
export function wordsIndexSource(words = loadWords()) {
  const head = [
    '<!-- GENERATED by scripts/gen-words-index.mjs from each word.json, README and emit.web.ts header. Do not edit: change those and run `node scripts/gen-words-index.mjs`. -->',
    '',
    '# Words — the index',
    '',
    'Every word (block), its variants, modifiers and keys, each with the ≤60-character',
    'info line `az explain` prints, and the file to edit for each concern. Read this',
    'first when asked to change a block; open the word\'s README and spec for the',
    'rules behind it.',
    '',
    '`packages/words/test/words-index.test.ts` regenerates this file and fails when',
    'the committed copy differs, so it always matches the code.',
    '',
    ...colourStepSource(),
    '## Where a change goes',
    '',
    ...table(['Request', 'Edit'], [
      ['The words on a page, which blocks, their order', "the site's `.az` file — `az explain <term>` for any term, `az check` after"],
      ['What a key accepts, its bounds, its info line', '`packages/words/<word>/word.json`'],
      ["One word's markup, layout or responsive styles", '`packages/words/<word>/emit.web.ts` (its `@az` header names the functions)'],
      ['Colours, spacing, type for every word', '`packages/theme/src/themes.ts` (theme data), `packages/theme/src/tokens.ts` (scales) — words read tokens only'],
      ['Buttons in every word', '`packages/target-web/src/actions.ts` (the button primitive)'],
      ['Menus, disclosures, carousel, lightbox, billing, reveal', '`packages/overlay/src/runtime/behaviours.ts`'],
      ['3D (hero `3d`, scene, gallery `orbit`)', '`packages/scene-runtime/src/runtime/`'],
      ['Sign-in forms in the browser', '`packages/auth-runtime/src/runtime/form.ts`'],
      ['A validation rule kind shared by words', '`packages/core/src/checks.ts`; the rule itself stays data in `word.json` `checks`'],
    ]),
    '',
    'Gates for any word change: `pnpm verify` (unit, typecheck, this index), `pnpm lint`',
    "(theme tokens), `pnpm gate words/<word>` (the 12-point gate, browsers), and",
    '`pnpm thumbnails <word> --verify`. CONTRIBUTING.md says which to run when.',
    '',
    '## Words',
    '',
    ...table(['Word', 'Info', 'Variants'], words.map((w) => [
      `[${code(w.manifest.name)}](#${w.manifest.name})`, w.manifest.description, (w.manifest.variants ?? []).map(code).join(' '),
    ])),
    '',
  ];
  return [...head, ...words.map(wordSection)].join('\n');
}

/** The README's words catalogue: word, info, variants, README link. */
export function catalogueSource(words = loadWords()) {
  return [
    CATALOGUE_START,
    ...table(['Word', 'Info', 'Variants', 'Docs'], words.map((w) => [
      code(w.manifest.name), w.manifest.description, (w.manifest.variants ?? []).map(code).join(' '),
      `[README](${WORDS_DIR}/${w.dir}/README.md)`,
    ])),
    CATALOGUE_END,
  ].join('\n');
}

/** `readme` with its catalogue block replaced; throws when the markers are missing. */
export function withCatalogue(readme, words = loadWords()) {
  const a = readme.indexOf(CATALOGUE_START);
  const b = readme.indexOf(CATALOGUE_END);
  if (a < 0 || b < a) throw new Error(`${README_FILE}: the words catalogue markers are missing`);
  return readme.slice(0, a) + catalogueSource(words) + readme.slice(b + CATALOGUE_END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const words = loadWords();
  writeFileSync(join(ROOT, INDEX_FILE), wordsIndexSource(words), 'utf8');
  const readme = join(ROOT, README_FILE);
  writeFileSync(readme, withCatalogue(readFileSync(readme, 'utf8'), words), 'utf8');
  console.log(`wrote ${INDEX_FILE} and the catalogue in ${README_FILE} (${words.length} words)`);
}
