/**
 * Generates packages/theme/src/ramps.ts — the accent hue ramps (PRD §6.1a).
 *
 * Ported from the M0 spike (spike-m0/src/shades.ts): every hue gets eleven
 * steps on ONE fixed lightness ladder, computed in OKLCH so the steps are
 * perceptually even and `accent.700` means the same lightness whatever the
 * hue. The output is DATA — literal colours are legal only in the theme's
 * data files (theme-spec §4) — so the maths lives here and the file it writes
 * is committed. packages/theme/test/ramps.test.ts regenerates and compares,
 * so the data can never drift from this generator.
 *
 * Run: node scripts/gen-ramps.mjs
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** The hues a site may name with `theme accent` — the spike's nine options. */
export const HUES = {
  violet: 292, indigo: 275, blue: 250, teal: 195, green: 148,
  lime: 122, amber: 75, orange: 48, rose: 15,
};

export const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

/** Fixed lightness per step — the ladder every hue shares (spike §shades). */
const LIGHTNESS = {
  50: 0.971, 100: 0.936, 200: 0.885, 300: 0.808, 400: 0.704,
  500: 0.606, 600: 0.523, 700: 0.448, 800: 0.379, 900: 0.312, 950: 0.221,
};

/** Chroma tapers at both ends — full chroma near white or black is muddy. */
const CHROMA_SCALE = {
  50: 0.18, 100: 0.32, 200: 0.55, 300: 0.78, 400: 0.94,
  500: 1.0, 600: 0.98, 700: 0.9, 800: 0.78, 900: 0.64, 950: 0.48,
};

/** Peak chroma, at step 500. */
const PEAK_CHROMA = 0.16;

const clamp01 = (n) => Math.min(1, Math.max(0, n));

/** OKLCH → sRGB bytes (Björn Ottosson's published matrices). */
function oklchToRgb(l, c, h) {
  const hr = (h * Math.PI) / 180;
  const a = c * Math.cos(hr);
  const b = c * Math.sin(hr);
  const l_ = l + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = l - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = l - 0.0894841775 * a - 1.291485548 * b;
  const L = l_ ** 3, M = m_ ** 3, S = s_ ** 3;
  return [
    +4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S,
    -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S,
    -0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S,
  ].map((v) => {
    const s = v <= 0.0031308 ? 12.92 * v : 1.055 * Math.pow(clamp01(v), 1 / 2.4) - 0.055;
    return Math.round(clamp01(s) * 255);
  });
}

/** sRGB bytes → the `hsl(H S% L%)` form every theme value uses (one decimal). */
function rgbToHsl([r, g, b]) {
  const R = r / 255, G = g / 255, B = b / 255;
  const max = Math.max(R, G, B), min = Math.min(R, G, B);
  const l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === R) h = ((G - B) / d + (G < B ? 6 : 0)) * 60;
    else if (max === G) h = ((B - R) / d + 2) * 60;
    else h = ((R - G) / d + 4) * 60;
  }
  const f = (n) => Math.round(n * 10) / 10;
  return `hsl(${f(h)} ${f(s * 100)}% ${f(l * 100)}%)`;
}

/** Every hue's eleven steps, as theme-value strings. */
export function buildRamps() {
  const out = {};
  for (const [name, hue] of Object.entries(HUES)) {
    out[name] = {};
    for (const step of STEPS) {
      out[name][step] = rgbToHsl(oklchToRgb(LIGHTNESS[step], PEAK_CHROMA * CHROMA_SCALE[step], hue));
    }
  }
  return out;
}

/** The TypeScript source of ramps.ts. */
export function rampsSource() {
  const ramps = buildRamps();
  const lines = [
    '/**',
    ' * @az module theme-ramps',
    ' * Purpose: the accent hue ramps — eleven OKLCH-even steps per hue (PRD §6.1a).',
    ' * Spec: docs/PRD.md §6.1a (accent) · docs/theme-spec.md §4 (a theme data file)',
    ' * Exports: ACCENT_RAMPS, RAMP_STEPS, ACCENT_HUE_DEGREES',
    ' * Edit guide: GENERATED by scripts/gen-ramps.mjs — change the generator and rerun it.',
    ' * Tests: packages/theme/test/ramps.test.ts, packages/theme/test/accent.test.ts',
    ' */',
    '',
    '// Raw colour values are legal here: this is theme DATA (theme-spec §4).',
    '',
    `export const RAMP_STEPS = [${STEPS.join(', ')}] as const;`,
    'export type RampStep = (typeof RAMP_STEPS)[number];',
    '',
    'export const ACCENT_RAMPS = {',
  ];
  for (const [name, steps] of Object.entries(ramps)) {
    lines.push(`  ${name}: {`);
    for (const step of STEPS) lines.push(`    ${step}: '${steps[step]}',`);
    lines.push('  },');
  }
  lines.push('} as const satisfies Record<string, Record<RampStep, string>>;', '',
    'export type AccentName = keyof typeof ACCENT_RAMPS;', '',
    '/** Each ramp\'s OKLCH hue angle, in degrees: what an accent pair\'s hue distance is measured on. */',
    'export const ACCENT_HUE_DEGREES = {',
    ...Object.entries(HUES).map(([name, hue]) => `  ${name}: ${hue},`),
    '} as const satisfies Record<AccentName, number>;', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = fileURLToPath(new URL('../packages/theme/src/ramps.ts', import.meta.url));
  writeFileSync(target, rampsSource(), 'utf8');
  console.log(`wrote ${target}`);
}
