/**
 * Regenerate packages/target-web/src/named-references.ts — HTML's named
 * character reference table (HTML §13.5), which decodeAttribute in
 * html-scan.ts reads attribute values by.
 *
 *     node scripts/gen-named-references.mjs                  # fetches SOURCE
 *     node scripts/gen-named-references.mjs ./entities.json  # a copy already downloaded
 *
 * The table is the HTML standard's published JSON, read ONCE here and
 * committed: a build never fetches anything, and the module is data in the
 * repo. The JSON's SHA-256 is pinned, so a changed table is never taken in
 * silently — on a mismatch the script stops; review the new table, then
 * update SHA256 below.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://html.spec.whatwg.org/entities.json';
const SHA256 = 'd741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6';
/** The whole download — the file is about 146KB; a stalled server fails, it is not waited on. */
const FETCH_MS = 30_000;
/** Characters per line of the generated strings, so the module diffs line by line. */
const LINE = 100;

const out = fileURLToPath(new URL('../packages/target-web/src/named-references.ts', import.meta.url));

async function source() {
  const local = process.argv[2];
  if (local) return readFileSync(local);
  const res = await fetch(SOURCE, { signal: AbortSignal.timeout(FETCH_MS) });
  if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

/** Words joined by spaces, wrapped at LINE characters. */
function wrap(words) {
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line && line.length + 1 + w.length > LINE) { lines.push(line); line = w; }
    else line = line ? `${line} ${w}` : w;
  }
  if (line) lines.push(line);
  return lines.join('\n');
}

const bytes = await source();
const digest = createHash('sha256').update(bytes).digest('hex');
if (digest !== SHA256) {
  throw new Error(`the table's SHA-256 is ${digest}, not the pinned ${SHA256} — review the new table, then update SHA256`);
}
const table = JSON.parse(bytes.toString('utf8'));

const entries = [];
const legacy = [];
for (const [key, { codepoints, characters }] of Object.entries(table)) {
  const m = /^&([A-Za-z0-9]+)(;?)$/.exec(key);
  if (!m) throw new Error(`unexpected name ${JSON.stringify(key)}`);
  if (String.fromCodePoint(...codepoints) !== characters) throw new Error(`${key}: codepoints and characters disagree`);
  if (m[2] === ';') {
    entries.push(`${m[1]}:${codepoints.map((c) => c.toString(16)).join('+')}`);
  } else {
    // Every name the table allows without `;` is also in it with one, for the same characters.
    if (table[`${key};`]?.characters !== characters) throw new Error(`${key} has no matching ${key};`);
    legacy.push(m[1]);
  }
}

writeFileSync(out, `/**
 * @az module named-references
 * Purpose: HTML's named character reference table, as data for decodeAttribute.
 * Spec: HTML §13.5 (named character references) · HTML §13.2.5.73 (named character reference state)
 * Exports: NAMED_REFERENCES, LEGACY_NAMES
 * Edit guide: regenerate with node scripts/gen-named-references.mjs — never edit by hand. Imports nothing — the CLI copies this file verbatim into az-vite/ beside html-scan.ts, which imports it.
 * Tests: packages/target-web/test/html-scan.test.ts
 */

/**
 * GENERATED by scripts/gen-named-references.mjs from ${SOURCE}
 * (SHA-256 ${SHA256}): ${entries.length + legacy.length} names.
 *
 * Every name the table spells with its \`;\`, as \`name:code points\` — the
 * code points in hexadecimal, joined by \`+\` where a name stands for two
 * (${entries.length} names).
 */
export const NAMED_REFERENCES = \`
${wrap(entries)}
\`;

/**
 * The names the table also allows WITHOUT their \`;\`, for historical reasons
 * — each stands for the same characters as its \`name;\` above (${legacy.length} names).
 */
export const LEGACY_NAMES = \`
${wrap(legacy)}
\`;
`, 'utf8');
process.stdout.write(`wrote ${out} (${entries.length} names with ';', ${legacy.length} also without)\n`);
