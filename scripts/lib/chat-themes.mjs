/**
 * The chat renderer's themes (chat-block-spec §22.3): for each of the six
 * themes, the chat word's panel as a site's page renders it — every
 * template an answer is drawn from — and its stylesheet, made by the same
 * compiler, emitters and stylesheet a site's build runs
 * (target-web chat-library.ts). `scripts/gen-chat-themes.mjs` writes them
 * into packages/chat-render/themes/; `chat-themes.test.mjs` (part of `pnpm
 * verify`) holds the committed files to what this makes, so a change to the
 * chat word or a theme that is not regenerated fails.
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compile } from '../../packages/core/src/index.ts';
import { THEMES } from '../../packages/theme/src/index.ts';
import { loadManifests } from '../../packages/cli/src/words.ts';
import { WEB_EMITTERS } from '../../packages/words/registry.ts';
import { checkPreset } from '../../packages/backend/src/chat-context.ts';
import { chatLibrarySet } from '../../packages/target-web/src/chat-library.ts';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const THEMES_DIR = 'packages/chat-render/themes';
const FIXTURE = fileURLToPath(new URL('./chat-themes.az', import.meta.url));

/** A generated file's first line: what it is, and how it is made again — never by hand. */
const generated = (what) => `/* GENERATED BY AZ — ${what}. Do not edit: run node scripts/gen-chat-themes.mjs. */\n`;

/** An emitted node as the renderer builds it: its tag, its attributes, its children — no style (every style is a class). */
function template(n) {
  if (typeof n === 'string') return n;
  if (n.style || n.states || n.below || n.reducedMotion || n.translucent) throw new Error(`chat themes: a ${n.tag} kept a style the compiler should have moved`);
  return { t: n.tag, ...(n.attrs && Object.keys(n.attrs).length > 0 ? { a: n.attrs } : {}), ...(n.children && n.children.length > 0 ? { c: n.children.map(template) } : {}) };
}

/** Every theme's files, `{ path, content }`, in theme order: a module of the shell, and its stylesheet. */
export function chatThemeFiles() {
  const manifests = loadManifests(fileURLToPath(new URL('../../packages/words/', import.meta.url)));
  const source = readFileSync(FIXTURE, 'utf8');
  const files = [];
  for (const name of Object.keys(THEMES)) {
    const r = compile(source.replace('theme midnight', `theme ${name}`), { manifests, checkAnswer: checkPreset });
    if (!r.ok || !r.spec) throw new Error(`chat themes: the fixture does not compile for ${name}: ${JSON.stringify(r.diagnostics.filter((d) => d.severity === 'error'))}`);
    const set = chatLibrarySet(r.spec, WEB_EMITTERS);
    files.push({
      path: `${THEMES_DIR}/${name}.ts`,
      content: `${generated(`the chat panel's templates for the ${name} theme, from the chat word (chat-block-spec §22.3)`)}import type { TemplateNode } from '../src/chat-templates.ts';

export const THEME = ${JSON.stringify(set.theme)};

export const SHELL: TemplateNode = ${JSON.stringify(template(set.shell), null, 1)};
`,
    });
    files.push({ path: `${THEMES_DIR}/${name}.css`, content: `${generated(`the chat renderer's stylesheet for the ${name} theme (chat-block-spec §22.3)`)}${set.css}` });
  }
  return files;
}

/** The files on disk that differ from what chatThemeFiles makes, by path. */
export function staleThemeFiles(files = chatThemeFiles()) {
  return files.filter((f) => {
    try {
      return readFileSync(`${ROOT}${f.path}`, 'utf8') !== f.content;
    } catch {
      return true;
    }
  }).map((f) => f.path);
}
